def t1_points(T1, L, pc, SCN):
    TB, AG, RG = T1["B_候选对真值收益"], T1["_agg"], T1["_rng"]
    b, c_, d_ = {"E": ("E4", "E12", "E13"), "X": ("X4", "X12", "X13")}[L]
    out = []
    for s in dict.fromkeys(TB.机制):
        h = TB[TB.机制 == s]

        def rng(pair, g):
            q = h[(h.候选对 == pair) & (h.轨 == g)]
            return (f"{pc(q.真值相对收益均值.min(), 2)}~{pc(q.真值相对收益均值.max(), 2)}"
                    f"（达 m {int(q.达m_分子.min())}–{int(q.达m_分子.max())}/{int(q.达m_分母.max())}）")

        def ag(nm):
            q = AG[(AG.机制 == s) & (AG.选择器 == nm)].iloc[0]
            return f"错误启用 {q.错误启用分子}/{q.错误启用分母}、漏启用 {q.漏启用分子}/{q.漏启用分母}"

        def pr(nm):
            q = RG[(RG.机制 == s) & (RG.选择器 == nm)].iloc[0]
            return f"{pc(q.条件均值最小, 3)}~{pc(q.条件均值最大, 3)}"

        out.append(f"- **{SCN.get(s, s)}**：HTFS_D 相对 P\\*_D 的真值收益 A 轨 {rng('D: HTFS_D vs P*_D', 'A')}、"
                   f"B 轨 {rng('D: HTFS_D vs P*_D', 'B')}；相对 S0\\*_D A 轨 {rng('D: HTFS_D vs S0*_D', 'A')}、"
                   f"B 轨 {rng('D: HTFS_D vs S0*_D', 'B')}（{b}）。FCT|P\\*：{ag('FCT|P*')}，部署后两轨等权相对 P\\*_D {pr('FCT|P*')}；"
                   f"CV_POINT_M|P\\*：{ag('CV_POINT_M|P*')}，{pr('CV_POINT_M|P*')}；MIX：{pr('MIX')}（{c_}、{d_}）。")
    return out


